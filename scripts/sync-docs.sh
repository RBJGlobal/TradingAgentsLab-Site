#!/usr/bin/env bash
#
# sync-docs.sh: copy the user-facing knowledge bases from the two app repos
# into this site's content/docs/<set>/ directories.
#
#   lite  <- TradingAgentsLab      (RBJGlobal/TradingAgentsLab)      docs/kb/*.md
#   pro   <- TradingAgentsLab-Pro  (RBJGlobal/TradingAgentsLab-Pro)  docs/kb/*.md
#
# Source of truth lives in the product repos so each KB ships with its code.
# This script keeps the site's bundled content in sync without the build
# pipeline needing the app repos at build time (Cloudflare Pages only sees
# this repo). Each set is replaced as a whole, so a page deleted upstream
# disappears here too. Add a redirect in public/_redirects when that happens.
#
# Usage:  npm run sync-docs
#
# Expects (defaults assume sibling checkouts):
#   $TAL_REPO      Lite app checkout, defaults to ../TradingAgents
#   $TAL_PRO_REPO  Pro app checkout,  defaults to ../TradingAgentsLab-Pro

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

sync_set() {
  local set="$1" src="$2"
  local dest="$ROOT/content/docs/$set"

  if [[ -z "$src" || ! -d "$src/docs/kb" ]]; then
    echo "✗ $set: could not find docs/kb under '$src'." >&2
    echo "  Set TAL_REPO / TAL_PRO_REPO, or run from a sibling layout." >&2
    exit 1
  fi

  mkdir -p "$dest"
  echo "→ $set: syncing from $src/docs/kb"
  rm -f "$dest"/*.md

  # Copy all .md files, excluding README.md (the site renders its own index).
  local copied=0 f bn
  for f in "$src"/docs/kb/*.md; do
    bn="$(basename "$f")"
    if [[ "$bn" == "README.md" ]]; then continue; fi
    cp "$f" "$dest/$bn"
    copied=$((copied + 1))
  done

  # Sync stamp so drift is detectable by inspection (gitignored). Records the
  # GitHub repo name, never a local path.
  local sha repo
  sha="$(git -C "$src" rev-parse --short HEAD 2>/dev/null || echo unknown)"
  repo="$(git -C "$src" remote get-url origin 2>/dev/null \
    | sed -E 's#^.*github\.com[:/]##; s#\.git$##' || true)"
  cat > "$dest/.sync-stamp" <<STAMP
# Auto-generated by scripts/sync-docs.sh. Do not edit manually.
set: $set
source_repo: ${repo:-unknown}
source_commit: $sha
synced_at_utc: $(date -u +"%Y-%m-%dT%H:%M:%SZ")
file_count: $copied
STAMP

  echo "✓ $set: synced $copied file(s) at source commit $sha."
}

sync_set lite "${TAL_REPO:-$(cd "$ROOT/../TradingAgents" 2>/dev/null && pwd || true)}"
sync_set pro "${TAL_PRO_REPO:-$(cd "$ROOT/../TradingAgentsLab-Pro" 2>/dev/null && pwd || true)}"
